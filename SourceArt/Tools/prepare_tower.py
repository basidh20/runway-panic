"""
prepare_tower.py - turn the delivered control tower into the pipeline assets SM_Prop_ControlTower and
SM_Prop_ControlTower_Collision (Blender 5.2).

The source file (GV-IS/ControlTower/ControlTower.blend, outside the repo; generated by its own text block
build_tower.py) is only read. The result is saved as SourceArt/Blender/Props/SM_Prop_ControlTower.blend, which
export_fbx.py then exports like every other model (both collections: --all).

What it changes, and why:
  1. Scale 0.7 (uniform, baked into the mesh data and the child locations): the tower was built at real size (roof
     21.55 m, footprint 19.8 x 14.8 m). At 0.7 the roof is at 15.1 m and the shaft base 5.3 m wide - the size of the
     World Builder's placeholder (roof 14.6 m, base 5 m), so it fits the same spot (-33, 28), the flight grid
     (top 24.5 m; antenna 18.4 m) and the hawk's tower vantage stays at the same height. Baked, not a Unity scale,
     so the prefab root stays (1, 1, 1) - the same rule as the aircraft.
  2. The 18 wall-pack lamps (one shared mesh, 18 objects) are joined into ONE object, Wall_Lights: in Unity every
     object is its own renderer, and each lamp has 2 submeshes (housing + emissive lens) = 36 draw calls per pass
     for 1,008 triangles. Joined: 2.
  3. Names: collection ControlTower_Asset -> SM_Prop_ControlTower (export_fbx.py routes "Prop" to Models/Props/),
     ControlTower_Collision -> SM_Prop_ControlTower_Collision; root empties -> ControlTower_Root /
     ControlTower_Collision_Root; materials M_X -> M_Tower_X (Unity looks materials up by name in Art/Materials/Props,
     and M_Charcoal / M_Gunmetal are too generic next to other props).
  4. UVs: the source UVs are box projections in metres (up to 13 units) and every part overlaps the others. The atlas
     needs ONE shared 0-1 square: the existing islands are kept (no new seams), cut along material borders, averaged
     to one texel density and packed together (margin 0.004 FRACTION, as the birds and the aircraft: 2.05 px at 256).
     The COL_ meshes are never textured, so their UVs stay as they are.

The collision meshes (6 closed convex prisms: shaft, platform, cab, roof, 2 utility blocks) are exported as their own
FBX; ArtControlTowerBuilder.cs turns each into a convex MeshCollider on the prefab.
The preview camera, sun and ground (collection Preview_Only) are kept for renders; they are not exported.

Usage (from the repo root):
  blender --background --python SourceArt/Tools/prepare_tower.py -- <in.blend> <out.blend>
"""
import sys

import bpy
from mathutils import Matrix, Vector

SCALE = 0.7
COLLECTIONS = {"ControlTower_Asset": "SM_Prop_ControlTower",
               "ControlTower_Collision": "SM_Prop_ControlTower_Collision"}
ROOTS = {"ControlTower": "ControlTower_Root", "ControlTower_Collision": "ControlTower_Collision_Root"}
LIGHTS_PREFIX, LIGHTS_JOINED = "Light_", "Wall_Lights"
MARGIN = 0.004


def world_bounds(objs):
    pts = [o.matrix_world @ Vector(c) for o in objs if o.type == "MESH" for c in o.bound_box]
    return Vector([min(p[i] for p in pts) for i in range(3)]), Vector([max(p[i] for p in pts) for i in range(3)])


def tri_count(meshes):
    return sum(len(p.vertices) - 2 for o in meshes for p in o.data.polygons)


def main():
    src, dst = sys.argv[sys.argv.index("--") + 1:][:2]
    bpy.ops.wm.open_mainfile(filepath=src)

    asset = bpy.data.collections["ControlTower_Asset"]
    collision = bpy.data.collections["ControlTower_Collision"]
    objs = list(asset.all_objects) + list(collision.all_objects)
    lo0, hi0 = world_bounds(list(asset.all_objects))
    tris0 = tri_count([o for o in asset.all_objects if o.type == "MESH"])

    # 1. Uniform scale. Every object has scale 1 and an identity parent inverse (checked); the lamps are rotated
    #    about Z only. A uniform scale commutes with rotation, so scaling each mesh around its own origin and every
    #    local location by the same factor scales the whole assembly.
    for o in objs:
        assert o.matrix_parent_inverse == Matrix.Identity(4) and tuple(o.scale) == (1, 1, 1), o.name
    for me in {o.data for o in objs if o.type == "MESH"}:   # the shared lamp mesh is scaled once
        me.transform(Matrix.Scale(SCALE, 4))
    for o in objs:
        o.location = o.location * SCALE
    bpy.context.view_layer.update()

    # 2. Join the lamps. Each gets its own copy of the shared mesh first (join and apply need single users), then
    #    the joined object's location/rotation is applied, so it sits at the root origin with no rotation, like the
    #    other parts (export_fbx.py warns about unapplied rotations).
    lights = sorted((o for o in asset.all_objects if o.type == "MESH" and o.name.startswith(LIGHTS_PREFIX)),
                    key=lambda o: o.name)
    lamp_mesh = lights[0].data
    for o in lights:
        o.data = o.data.copy()
    bpy.data.meshes.remove(lamp_mesh)
    bpy.ops.object.select_all(action="DESELECT")
    for o in lights:
        o.select_set(True)
    bpy.context.view_layer.objects.active = lights[0]
    bpy.ops.object.join()
    joined = bpy.context.view_layer.objects.active
    bpy.ops.object.transform_apply(location=True, rotation=True, scale=False)
    joined.name = joined.data.name = LIGHTS_JOINED
    print("[prepare_tower] joined %d lamps into %s" % (len(lights), LIGHTS_JOINED))

    # 3. Names.
    for old, new in COLLECTIONS.items():
        bpy.data.collections[old].name = new
    for old, new in ROOTS.items():
        bpy.data.objects[old].name = new
    asset_meshes = [o for o in asset.all_objects if o.type == "MESH"]
    for m in {m for o in asset_meshes for m in o.data.materials if m}:
        m.name = "M_Tower_" + m.name[2:]

    # 4. One shared UV square for all visible parts: keep the islands, cut at material borders, equalise texel
    #    density, pack. Each material's faces are shifted by a different small offset, so neighbours of different
    #    materials no longer share UVs (an island that mixes two materials cannot get one flat atlas colour); the
    #    island shapes stay the same and pack_islands moves them apart anyway. Same steps as prepare_aircraft.py.
    for me in {o.data for o in asset_meshes}:
        uv = me.uv_layers.active.data
        for poly in me.polygons:
            for li in poly.loop_indices:
                uv[li].uv.x += poly.material_index * 0.01
    bpy.ops.object.select_all(action="DESELECT")
    for o in asset_meshes:
        o.select_set(True)
    bpy.context.view_layer.objects.active = asset_meshes[0]
    bpy.ops.object.mode_set(mode="EDIT")
    bpy.ops.mesh.select_all(action="SELECT")
    bpy.ops.uv.select_all(action="SELECT")
    bpy.ops.uv.average_islands_scale()
    bpy.ops.uv.pack_islands(rotate=True, margin_method="FRACTION", margin=MARGIN, shape_method="CONCAVE")
    bpy.ops.object.mode_set(mode="OBJECT")

    lo1, hi1 = world_bounds(asset_meshes)
    tris1 = tri_count(asset_meshes)
    size0, size1 = hi0 - lo0, hi1 - lo1
    print("[prepare_tower] size before %.2f x %.2f x %.2f m (X, Y, Z height)" % tuple(size0))
    print("[prepare_tower] size after  %.2f x %.2f x %.2f m, min Z %.4f" % (*size1, lo1.z))
    print("[prepare_tower] tris %d -> %d, %d visible objects" % (tris0, tris1, len(asset_meshes)))
    for o in sorted(collision.all_objects, key=lambda o: o.name):
        if o.type == "MESH":
            lo, hi = world_bounds([o])
            print("[prepare_tower] %-20s x %6.2f..%6.2f  y %6.2f..%6.2f  z %6.2f..%6.2f"
                  % (o.name, lo.x, hi.x, lo.y, hi.y, lo.z, hi.z))
    assert tris0 == tris1
    assert all(abs(size1[i] - size0[i] * SCALE) < 1e-3 for i in range(3)), "scale did not apply uniformly"

    bpy.ops.wm.save_as_mainfile(filepath=dst, compress=False)
    print("[prepare_tower] saved " + dst)


main()
