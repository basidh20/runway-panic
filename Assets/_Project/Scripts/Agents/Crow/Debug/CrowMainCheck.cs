#if UNITY_EDITOR
using System.Collections;
using System.Collections.Generic;
using System.IO;
using System.Text;
using RunwayPanic.AI;
using RunwayPanic.Core;
using RunwayPanic.Interaction;
using RunwayPanic.Player;
using UnityEditor;
using UnityEngine;

namespace RunwayPanic.Agents.Crow
{
    /// <summary>
    /// Tools > IS > Crow > Run Main Integration Check (in Play mode, in Main): plays the crow in the real level and
    /// writes pass/fail results to <c>Docs/IS/Crow/main_integration.md</c>.
    /// <para>
    /// What the crow needs but Main may not have yet (a <see cref="FlightGrid"/>, <c>P_CrowSetup_Main</c>) is added for
    /// this Play session only and reported as missing — the scene file is never changed; the World Builder adds them.
    /// </para>
    /// Checks: crows find A* paths and patrol; approach the player; steal Main's pickups and deliver them to a stash;
    /// guard the shelter exit while the player hides; hold a funeral and enrage when one dies.
    /// </summary>
    public sealed class CrowMainCheck : MonoBehaviour
    {
        private const string CrowPrefabPath = "Assets/_Project/Prefabs/Birds/P_Bird_Crow.prefab";
        private const string SetupPrefabPath = "Assets/_Project/Prefabs/Birds/Crow/P_CrowSetup_Main.prefab";
        private const string ReportPath = "Docs/IS/Crow/main_integration.md";

        private readonly StringBuilder report = new StringBuilder();
        private readonly List<CrowBrain> crows = new List<CrowBrain>();
        private readonly Dictionary<CrowBrain, HashSet<CrowState>> seen = new Dictionary<CrowBrain, HashSet<CrowState>>();

        private PlayerController player;
        private PlayerHealth health;
        private GameObject crowPrefab;
        private int passed, failed;

        [MenuItem("Tools/IS/Crow/Run Main Integration Check")]
        private static void Run()
        {
            if (!EditorApplication.isPlaying)
            {
                Debug.LogWarning("[CrowMain] Open Main and enter Play mode first.");
                return;
            }

            if (FindAnyObjectByType<CrowMainCheck>() == null)
                new GameObject("[CrowMainCheck]").AddComponent<CrowMainCheck>();
        }

        private IEnumerator Start()
        {
            player = FindAnyObjectByType<PlayerController>();
            health = player != null ? player.GetComponent<PlayerHealth>() : null;
            crowPrefab = AssetDatabase.LoadAssetAtPath<GameObject>(CrowPrefabPath);
            if (player == null || crowPrefab == null)
            {
                Debug.LogError("[CrowMain] Needs a player in the scene and the crow prefab.");
                yield break;
            }

            CrowStats.Reset();
            report.AppendLine("# Crow in Main — integration check");
            report.AppendLine($"Scene `{UnityEngine.SceneManagement.SceneManager.GetActiveScene().name}`, {System.DateTime.Now:yyyy-MM-dd HH:mm}. " +
                              "Generated by `Tools > IS > Crow > Run Main Integration Check`.");
            report.AppendLine();
            report.AppendLine("## What the level provides");
            yield return ProvideMissing();

            report.AppendLine();
            report.AppendLine("## Behaviours");
            report.AppendLine("| Check | Result | Detail |");
            report.AppendLine("|---|---|---|");

            yield return Patrol();
            yield return ApproachPlayer();
            yield return Theft();
            yield return Vigil();
            yield return Funeral();

            report.AppendLine();
            report.AppendLine($"**{passed} passed, {failed} failed.**");
            Directory.CreateDirectory(Path.GetDirectoryName(ReportPath));
            File.WriteAllText(ReportPath, report.ToString());
            Debug.Log($"[CrowMain] Finished: {passed} passed, {failed} failed — {ReportPath}");

            foreach (CrowBrain crow in crows)
                if (crow != null)
                    Destroy(crow.gameObject);
        }

        private void Update()
        {
            if (health != null && health.CurrentHP < health.MaxHP * 0.6f)
                health.ResetHealth(); // keep the player alive; this checks the crows

            foreach (CrowBrain crow in crows)
                if (crow != null && seen.TryGetValue(crow, out HashSet<CrowState> states))
                    states.Add(crow.State);
        }

        // ---------- Level ----------

        private IEnumerator ProvideMissing()
        {
            bool hasGrid = FlightGrid.Instance != null;
            if (!hasGrid)
                new GameObject("[FlightGrid — test only]").AddComponent<FlightGrid>();
            report.AppendLine($"- FlightGrid: {(hasGrid ? "✅ in the scene" : "❌ **missing** — added for this test only (World Builder: add one)")}");

            bool hasSetup = FindAnyObjectByType<ShelterZone>() != null;
            if (!hasSetup)
                PrefabUtility.InstantiatePrefab(AssetDatabase.LoadAssetAtPath<GameObject>(SetupPrefabPath));
            report.AppendLine($"- Crow setup (stashes, shelter zones, exits): {(hasSetup ? "✅ in the scene" : "❌ **missing** — `P_CrowSetup_Main` added for this test only (World Builder: drag it in)")}");

            yield return null;
            int pickups = FindObjectsByType<Pickup>().Length;
            report.AppendLine($"- Pickups to steal: {(pickups > 0 ? $"✅ {pickups}" : "❌ none")}");
            var stashes = new List<BirdPoint>();
            BirdPoint.GetAll(BirdPointType.Stash, stashes);
            report.AppendLine($"- Stash markers: {stashes.Count}; ShelterZones: {FindObjectsByType<ShelterZone>().Length}");
        }

        // ---------- Behaviours ----------

        private IEnumerator Patrol()
        {
            // Far from the player (no approach yet), each in a different quarter of the airport.
            Vector3 p = player.transform.position;
            foreach (Vector3 offset in new[] { new Vector3(35f, 0f, 20f), new Vector3(-35f, 0f, 22f), new Vector3(35f, 0f, -25f) })
            {
                CrowBrain crow = Spawn(FlyablePoint(p + offset, 8f));
                if (crow != null)
                    seen[crow] = new HashSet<CrowState>();
            }

            var start = new Dictionary<CrowBrain, Vector3>();
            foreach (CrowBrain crow in crows)
                start[crow] = crow.transform.position;
            yield return new WaitForSeconds(6f);

            int moving = 0;
            foreach (CrowBrain crow in crows)
                if (crow != null && Vector3.Distance(start[crow], crow.transform.position) > 5f)
                    moving++;
            Result("Crows fly A* routes around the level", moving == crows.Count, $"{moving} of {crows.Count} moved more than 5 m in 6 s");
        }

        private IEnumerator ApproachPlayer()
        {
            CrowBrain crow = Spawn(FlyablePoint(player.transform.position + new Vector3(18f, 0f, 0f), 6f));
            seen[crow] = new HashSet<CrowState>();
            float until = Time.time + 8f;
            yield return new WaitUntil(() => crow == null || seen[crow].Contains(CrowState.Attack) || Time.time > until);
            bool ok = crow != null && (seen[crow].Contains(CrowState.Approach) || seen[crow].Contains(CrowState.StealFly));
            Result("A crow near the player approaches (or goes for loot)", ok, crow != null ? "states: " + string.Join(", ", seen[crow]) : "crow lost");
        }

        // Counted from the start of the run (CrowStats reset in Start): a crow may start stealing during the earlier checks.
        private IEnumerator Theft()
        {
            float until = Time.time + 35f;
            yield return new WaitUntil(() => CrowStats.TheftsSucceeded > 0 || Time.time > until);
            Result("Crows steal Main's pickups", CrowStats.TheftsAttempted > 0, $"{CrowStats.TheftsAttempted} thefts started");
            Result("…and deliver them to a stash", CrowStats.TheftsSucceeded > 0, $"{CrowStats.TheftsSucceeded} delivered");
        }

        private IEnumerator Vigil()
        {
            ShelterZone zone = null;
            foreach (ShelterZone z in FindObjectsByType<ShelterZone>())
                if (zone == null || z.Group == "ShelterA")
                    zone = z;
            if (zone == null)
            {
                Result("Crows guard the shelter while the player hides", false, "no ShelterZone");
                yield break;
            }

            Vector3 outside = player.transform.position;
            Teleport(zone.Centre + Vector3.down * (zone.GetComponent<BoxCollider>().bounds.extents.y - 0.1f));
            float until = Time.time + 14f;
            yield return new WaitUntil(() => CountIn(CrowState.Vigil) > 0 && AllVigilSettled() || Time.time > until);
            int guarding = CountIn(CrowState.Vigil);
            Result("Crows guard the shelter while the player hides", guarding > 0,
                $"player inside: {ShelterZone.PlayerInside == zone}; {guarding} crow(s) at the exit");

            Teleport(outside);
            yield return new WaitForSeconds(1f);
            Result("…and attack the moment the player comes out", CountIn(CrowState.Enraged) > 0 || guarding == 0,
                $"{CountIn(CrowState.Enraged)} enraged");
            yield return new WaitForSeconds(3f);
        }

        private IEnumerator Funeral()
        {
            Vector3 centre = FlyablePoint(player.transform.position + new Vector3(-20f, 0f, -10f), 7f);
            CrowBrain victim = Spawn(centre);
            CrowBrain mourner = Spawn(FlyablePoint(centre + new Vector3(4f, 0f, 3f) - Vector3.up * 7f, 7f));
            seen[mourner] = new HashSet<CrowState>();
            yield return new WaitForSeconds(0.5f);

            victim.GetComponent<BirdHealth>().TakeDamage(10000f, WeaponRarity.Legendary);
            float until = Time.time + 6f;
            yield return new WaitUntil(() => mourner == null || seen[mourner].Contains(CrowState.Enraged) || Time.time > until);
            bool ok = mourner != null && seen[mourner].Contains(CrowState.Funeral);
            Result("A nearby crow mourns, then enrages", ok && seen[mourner].Contains(CrowState.Enraged),
                mourner != null ? "states: " + string.Join(", ", seen[mourner]) : "crow lost");
        }

        // ---------- Helpers ----------

        private CrowBrain Spawn(Vector3 position)
        {
            CrowBrain crow = Instantiate(crowPrefab, position, Quaternion.identity).GetComponent<CrowBrain>();
            crows.Add(crow);
            return crow;
        }

        // A flyable point near 'ground' at 'height' (searches outward if that spot is inside geometry).
        private static Vector3 FlyablePoint(Vector3 ground, float height)
        {
            Vector3 p = new Vector3(ground.x, height, ground.z);
            for (int r = 0; r < 6; r++)
            for (int a = 0; a < 8; a++)
            {
                Vector3 candidate = p + Quaternion.AngleAxis(a * 45f, Vector3.up) * Vector3.forward * (r * 3f);
                if (PathService.Current.IsFlyable(candidate))
                    return candidate;
            }

            return p;
        }

        private int CountIn(CrowState state)
        {
            int n = 0;
            foreach (CrowBrain crow in crows)
                if (crow != null && crow.enabled && crow.State == state)
                    n++;
            return n;
        }

        private bool AllVigilSettled()
        {
            foreach (CrowBrain crow in crows)
                if (crow != null && crow.State == CrowState.Vigil && crow.GetComponent<IBirdMotor>().Velocity.sqrMagnitude > 0.05f)
                    return false;
            return true;
        }

        private void Teleport(Vector3 position)
        {
            var controller = player.GetComponent<CharacterController>();
            controller.enabled = false;
            player.transform.position = position;
            controller.enabled = true;
        }

        private void Result(string check, bool ok, string detail)
        {
            if (ok) passed++; else failed++;
            report.AppendLine($"| {check} | {(ok ? "✅ pass" : "❌ fail")} | {detail} |");
        }
    }
}
