    /// <summary>
    /// Tools > IS > Crow > Run Evidence Playtest (in Play mode, in Sandbox_IS_Crow): a scripted playtest that measures
    /// the crow's IS techniques and writes the results to <c>Docs/IS/Crow/evidence.md</c> and
    /// <c>Docs/IS/Crow/path_comparison.png</c> — the evidence table in NOTES.md §7.
    /// <list type="number">
    /// <item>Grudge: three crows are "shot" from one spot (exactly like real shots: <c>PlayerShooting.ShotFired</c>, then
    /// damage), so the danger map is stamped by the real death path.</item>
    /// <item>A* with vs without the danger map, across the kill zone: length, danger crossed, and a picture.</item>
    /// <item>Approach choices for crows all around the player, before and after the kills (the crows' own scoring
    /// call), plus a live crow.</item>
    /// <item>Forgetting: danger at the shooter's spot, then one half-life later.</item>
    /// <item>Thefts in a live session; one thief shot while carrying.</item>
    /// <item>Script cost of six crows plus the map (profiler markers CrowBrain.Update, CrowDangerMap.Update).</item>
    /// </list>
    /// Editor-only test code: the player is kept alive and nothing is saved to the scene.
    /// </summary>
    public sealed class CrowEvidenceRun : MonoBehaviour
    {
        private const string CrowPrefabPath = "Assets/_Project/Prefabs/Birds/P_Bird_Crow.prefab";
        private const string OutputFolder = "Docs/IS/Crow";
        private const int ApproachBearings = 8;
        private const float CrowDistance = 20f;  // crows placed this far from the player
        private const float FlyHeight = 6f;
        private const float KillDistance = 12f;
        private const float PathHalfSpan = 22f;  // path test: from one side of the player to the other
        private const float TheftSeconds = 50f;
        private const float CostSeconds = 5f;
        private const int ImageSize = 512;
        private const float ImageMetres = 64f;

        private readonly StringBuilder report = new StringBuilder();
        private readonly List<GameObject> spawned = new List<GameObject>();

        private GameObject crowPrefab;
        private CrowStrategyConfig config;
        private CrowDangerMap map;
        private PlayerController player;
        private PlayerHealth health;
        private PlayerShooting shooting;
        private Vector3 home;      // the player's feet: the "camping spot"
        private Vector3 killDir;   // flat direction from home to the killed crows

        /// <summary>True once the report has been written.</summary>
        public bool Finished { get; private set; }

        [MenuItem("Tools/IS/Crow/Run Evidence Playtest")]
        private static void Run()
        {
            if (!EditorApplication.isPlaying)
            {
                Debug.LogWarning("[CrowEvidence] Enter Play mode in Sandbox_IS_Crow first.");
                return;
            }

            if (FindAnyObjectByType<CrowEvidenceRun>() == null)
                new GameObject("[CrowEvidenceRun]").AddComponent<CrowEvidenceRun>();
        }

        private IEnumerator Start()
        {
            if (!Setup())
                yield break;

            Line("# Crow evidence — scripted playtest");
            Line($"Scene `{UnityEngine.SceneManagement.SceneManager.GetActiveScene().name}`, {System.DateTime.Now:yyyy-MM-dd HH:mm}. " +
                 $"Player at {home:F1}. Generated by `Tools > IS > Crow > Run Evidence Playtest`.");
            Line();

            List<(float bearing, float chosen, float danger)> before = ApproachChoices();

            yield return KillThreeFromHome();
            float stampTime = Time.time;
            float dangerAtHome = map.GetDanger(home);

            List<(float bearing, float chosen, float danger)> after = ApproachChoices();
            ReportPaths();
            ReportApproaches(before, after);
            yield return LiveApproach();

            // Forgetting is sampled exactly one half-life after the kills, while the theft session runs.
            float dangerLater = -1f, laterSeconds = 0f;
            StartCoroutine(SampleLater(config.DangerHalfLife, () =>
            {
                dangerLater = map.GetDanger(home);
                laterSeconds = Time.time - stampTime;
            }));

            yield return TheftSession();

            yield return new WaitUntil(() => dangerLater >= 0f);
            ReportDecay(dangerAtHome, dangerLater, laterSeconds);

            yield return ScriptCost();

            WriteReport();
            Cleanup();
            Finished = true;
        }

        // ---------- Setup ----------

        private bool Setup()
        {
            crowPrefab = AssetDatabase.LoadAssetAtPath<GameObject>(CrowPrefabPath);
            player = FindAnyObjectByType<PlayerController>();
            if (crowPrefab == null || player == null)
            {
                Debug.LogError("[CrowEvidence] Needs the crow prefab and a player in the scene.");
                return false;
            }

            health = player.GetComponent<PlayerHealth>();
            shooting = player.GetComponent<PlayerShooting>();
            config = crowPrefab.GetComponent<CrowBrain>().Config;
            home = player.transform.position;

            foreach (CrowBrain crow in FindObjectsByType<CrowBrain>())
                Destroy(crow.gameObject);

            map = CrowDangerMap.GetOrCreate(config);
            map.Clear();
            CrowStats.Reset();

            killDir = FindOpenDirection();
            SetPickupsActive(false); // crows approach instead of stealing until the theft session
            return true;
        }

        private void Update()
        {
            // Keep the player alive: the evidence is about the crows.
            if (health != null && health.CurrentHP < health.MaxHP * 0.6f)
                health.ResetHealth();
        }

        // The first compass direction with open air for the kills and the path test.
        private Vector3 FindOpenDirection()
        {
            for (int i = 0; i < 8; i++)
            {
                Vector3 dir = Quaternion.AngleAxis(i * 45f, Vector3.up) * Vector3.forward;
                Vector3 side = Vector3.Cross(Vector3.up, dir);
                if (Flyable(home + dir * KillDistance) && Flyable(home + side * PathHalfSpan) && Flyable(home - side * PathHalfSpan))
                    return dir;
            }

            return Vector3.forward;
        }

        private static bool Flyable(Vector3 ground) => PathService.Current.IsFlyable(ground + Vector3.up * FlyHeight);

        // ---------- Grudge: three kills from one spot ----------

        private IEnumerator KillThreeFromHome()
        {
            Vector3 side = Vector3.Cross(Vector3.up, killDir);
            FieldInfo shotEvent = typeof(PlayerShooting).GetField("ShotFired", BindingFlags.NonPublic | BindingFlags.Instance);

            for (int i = -1; i <= 1; i++)
            {
                Vector3 position = home + killDir * KillDistance + side * (i * 1.5f) + Vector3.up * 5f;
                CrowBrain crow = Spawn(position);
                yield return new WaitForSeconds(0.2f);

                // Exactly what a real shot does: PlayerShooting.ShotFired (the hub records the origin), then damage.
                var bird = crow.GetComponent<BirdHealth>();
                var fired = shotEvent?.GetValue(shooting) as System.Action<Vector3, Vector3, IDamageable>;
                fired?.Invoke(home + Vector3.up * 1.4f, crow.transform.position, bird);
                bird.TakeDamage(10000f, WeaponRarity.Legendary);
                yield return new WaitForSeconds(0.3f);
            }

            Line("## 1. Grudge: danger written by crow deaths");
            Line($"Three crows shot from the player's spot, {KillDistance} m away. Danger stamps: **{CrowStats.DangerStamps}**. " +
                 $"Danger at the shooter's spot: **{map.GetDanger(home):F2}**; hottest cell: **{map.HottestCell:F2}** " +
                 $"(max {config.maxDanger}); total in the map: {map.TotalDanger:F1}.");
            Line();
        }

        // ---------- A* with vs without danger ----------

        private void ReportPaths()
        {
            Vector3 side = Vector3.Cross(Vector3.up, killDir);
            Vector3 from = home + side * PathHalfSpan + Vector3.up * FlyHeight;
            Vector3 to = home - side * PathHalfSpan + Vector3.up * FlyHeight;

            var clear = new List<Vector3>();
            var careful = new List<Vector3>();
            bool okClear = PathService.Current.TryFindPath(from, to, null, clear);
            bool okCareful = PathService.Current.TryFindPath(from, to, new List<ICostModifier> { map }, careful);
            clear.Insert(0, from);
            careful.Insert(0, from);

            Line("## 2. A* with and without the danger map");
            Line($"Same flight across the kill zone ({PathHalfSpan * 2:F0} m, side to side past the player). Found: {okClear} / {okCareful}.");
            Line();
            Line("| Path | Length | Danger crossed (∫ danger ds) | Highest danger on the way |");
            Line("|---|---:|---:|---:|");
            PathRow("Without danger costs", clear);
            PathRow("With danger costs (what crows fly)", careful);
            Line();
            Line("![paths](path_comparison.png)");
            Line();
            Line("*Red: remembered danger. Blue: path without danger costs. Green: path with danger costs. White: the player's spot. " +
                 "Black: where crows died. Grey: blocked at flight height.*");
            Line();

            DrawImage(clear, careful, Path.Combine(OutputFolder, "path_comparison.png"));
        }

        private void PathRow(string label, List<Vector3> path)
        {
            float length = 0f, crossed = 0f, highest = 0f;
            for (int i = 1; i < path.Count; i++)
            {
                float segment = Vector3.Distance(path[i - 1], path[i]);
                length += segment;
                int steps = Mathf.Max(1, Mathf.CeilToInt(segment / 0.5f));
                for (int s = 1; s <= steps; s++)
                {
                    float d = map.GetDanger(Vector3.Lerp(path[i - 1], path[i], s / (float)steps));
                    crossed += d * segment / steps;
                    highest = Mathf.Max(highest, d);
                }
            }

            Line($"| {label} | {length:F1} m | {crossed:F1} | {highest:F2} |");
        }

        // ---------- Approach choices ----------

        // For crows all around the player: the approach direction the crow's own scoring picks (no previous approach).
        private List<(float bearing, float chosen, float danger)> ApproachChoices()
        {
            var results = new List<(float, float, float)>();
            var candidates = new ApproachPointSelector.Candidate[config.approachSamples];
            for (int i = 0; i < ApproachBearings; i++)
            {
                float bearing = i * 360f / ApproachBearings;
                Vector3 crow = home + Quaternion.AngleAxis(bearing, Vector3.up) * killDir * CrowDistance + Vector3.up * FlyHeight;
                ApproachPointSelector.Select(home, crow, map, PathService.Current, config.approachSamples, config.approachRingRadius,
                    config.approachHeight, Vector3.zero, candidates, out Vector3 point, out Vector3 direction);
                results.Add((Wrap(bearing), Vector3.SignedAngle(killDir, direction, Vector3.up), map.GetDanger(point)));
            }

            return results;
        }

        private void ReportApproaches(List<(float bearing, float chosen, float danger)> before,
            List<(float bearing, float chosen, float danger)> after)
        {
            Line("## 3. Where crows choose to come from");
            Line("Bearings in degrees from the line of fire (0° = straight down the kill line). Each crow starts 20 m away at that bearing.");
            Line();
            Line("| Crow at | Chosen before kills | Danger there | Chosen after kills | Danger there |");
            Line("|---:|---:|---:|---:|---:|");
            int intoFireBefore = 0, intoFireAfter = 0;
            for (int i = 0; i < before.Count; i++)
            {
                Line($"| {before[i].bearing:F0}° | {before[i].chosen:F0}° | {before[i].danger:F2} | {after[i].chosen:F0}° | {after[i].danger:F2} |");
                if (Mathf.Abs(before[i].chosen) < 30f) intoFireBefore++;
                if (Mathf.Abs(after[i].chosen) < 30f) intoFireAfter++;
            }

            Line();
            Line($"Approaches within 30° of the line of fire: **{intoFireBefore} of {before.Count} before**, **{intoFireAfter} of {after.Count} after** the kills.");
            Line();
        }

        private IEnumerator LiveApproach()
        {
            FieldInfo approachField = typeof(CrowBrain).GetField("approachDirection", BindingFlags.NonPublic | BindingFlags.Instance);
            CrowBrain crow = Spawn(home + killDir * CrowDistance + Vector3.up * FlyHeight); // starts right on the kill line

            float until = Time.time + 6f;
            yield return new WaitUntil(() => crow == null || crow.State == CrowState.Approach || Time.time > until);
            yield return new WaitForSeconds(0.2f);

            string result = "did not start an approach";
            if (crow != null && approachField != null && crow.State == CrowState.Approach)
            {
                var dir = (Vector3)approachField.GetValue(crow);
                result = $"approached from **{Vector3.SignedAngle(killDir, dir, Vector3.up):F0}°** off the line of fire " +
                         $"(danger at its approach point {map.GetDanger(home + dir * config.approachRingRadius):F2})";
            }

            Line($"Live crow started on the kill line, 20 m out: {result}.");
            Line();
            Despawn(crow);
        }

        // ---------- Thefts ----------

        private IEnumerator TheftSession()
        {
            SetPickupsActive(true);
            int pickups = FindObjectsByType<Pickup>().Length;
            var thieves = new List<CrowBrain>();
            Vector3 away = -killDir; // away from the danger, so the session does not stamp near the player's spot
            for (int i = 0; i < 3; i++)
                thieves.Add(Spawn(home + Quaternion.AngleAxis(-60f + i * 60f, Vector3.up) * away * 25f + Vector3.up * FlyHeight));

            // Shoot the first thief in flight (away from the player's spot, so no danger lands there); the session
            // ends once a theft has been delivered and one recovered, or after TheftSeconds.
            bool shotThief = false;
            float start = Time.time;
            while (Time.time - start < TheftSeconds && (CrowStats.TheftsSucceeded == 0 || CrowStats.TheftsRecovered == 0))
            {
                if (!shotThief)
                {
                    foreach (CrowBrain crow in thieves)
                    {
                        if (crow == null || !crow.enabled || !crow.IsCarrying || (crow.transform.position - home).sqrMagnitude < 15f * 15f)
                            continue;
                        crow.GetComponent<BirdHealth>().TakeDamage(10000f, WeaponRarity.Legendary);
                        shotThief = true;
                        break;
                    }
                }

                yield return null;
            }

            // After delivery: does any crow go for loot that was already delivered?
            FieldInfo targetField = typeof(CrowBrain).GetField("targetPickup", BindingFlags.NonPublic | BindingFlags.Instance);
            int stashedTargeted = 0;
            float watchEnd = Time.time + 10f;
            while (Time.time < watchEnd)
            {
                foreach (CrowBrain crow in thieves)
                    if (crow != null && crow.State == CrowState.StealFly &&
                        CrowPickupClaims.IsStashed(targetField?.GetValue(crow) as Pickup))
                        stashedTargeted++;
                yield return null;
            }

            Line("## 4. Thefts");
            Line($"A {Time.time - start:F0} s session with three crows and {pickups} pickups in the scene; the first thief was shot in flight.");
            Line();
            Line("| Tried | Delivered to a stash | Recovered (thief shot) |");
            Line("|---:|---:|---:|");
            Line($"| {CrowStats.TheftsAttempted} | {CrowStats.TheftsSucceeded} | {CrowStats.TheftsRecovered} |");
            Line();
            Line($"Delivered loot left alone for the next 10 s: **{(stashedTargeted == 0 ? "yes" : "no")}** " +
                 "(a delivered pickup is never stolen again until the player takes it back).");
            Line();

            foreach (CrowBrain crow in thieves)
                Despawn(crow);
        }

        // ---------- Forgetting ----------

        private static IEnumerator SampleLater(float seconds, System.Action sample)
        {
            yield return new WaitForSeconds(seconds);
            sample();
        }

        private void ReportDecay(float start, float later, float seconds)
        {
            int steps = Mathf.FloorToInt(seconds / config.dangerDecayInterval);
            float expected = start * Mathf.Pow(config.dangerDecayFactor, steps);
            Line("## 5. Forgetting");
            Line($"Danger at the shooter's spot: **{start:F2}** when stamped, **{later:F2}** after {seconds:F0} s " +
                 $"({steps} decay steps; expected {expected:F2}). Ratio **{(start > 0f ? later / start : 0f):F2}** — " +
                 $"the configured half-life is {config.DangerHalfLife:F1} s.");
            Line();
        }

        // ---------- Script cost ----------

        private IEnumerator ScriptCost()
        {
            var crows = new List<CrowBrain>();
            for (int i = 0; i < 6; i++)
                crows.Add(Spawn(home + Quaternion.AngleAxis(i * 60f + 30f, Vector3.up) * killDir * 24f + Vector3.up * FlyHeight));

            yield return new WaitForSeconds(1f);
            using (var brains = ProfilerRecorder.StartNew(ProfilerCategory.Scripts, "CrowBrain.Update", 2000))
            using (var mapUpdates = ProfilerRecorder.StartNew(ProfilerCategory.Scripts, "CrowDangerMap.Update", 2000))
            {
                yield return new WaitForSeconds(CostSeconds);
                (float avgBrain, float maxBrain, int frames) = Summarise(brains);
                (float avgMap, float maxMap, _) = Summarise(mapUpdates);

                Line("## 6. Script cost");
                Line($"Six crows (decisions, A* searches included) and the danger map, {frames} frames in the Editor " +
                     "(a build is faster):");
                Line();
                Line("| Marker | Average per frame | Worst frame |");
                Line("|---|---:|---:|");
                Line($"| CrowBrain.Update (all 6 crows) | {avgBrain:F3} ms | {maxBrain:F3} ms |");
                Line($"| CrowDangerMap.Update | {avgMap:F3} ms | {maxMap:F3} ms |");
                Line($"| **Total** | **{avgBrain + avgMap:F3} ms** | |");
                Line();
            }

            foreach (CrowBrain crow in crows)
                Despawn(crow);
        }

        private static (float avg, float max, int count) Summarise(ProfilerRecorder recorder)
        {
            int count = recorder.Count;
            if (count == 0)
                return (0f, 0f, 0);
            double sum = 0, max = 0;
            for (int i = 0; i < count; i++)
            {
                double ms = recorder.GetSample(i).Value * 1e-6; // ns → ms
                sum += ms;
                if (ms > max) max = ms;
            }

            return ((float)(sum / count), (float)max, count);
        }

        // ---------- Picture ----------

        private void DrawImage(List<Vector3> clear, List<Vector3> careful, string file)
        {
            var texture = new Texture2D(ImageSize, ImageSize, TextureFormat.RGB24, false);
            var pixels = new Color32[ImageSize * ImageSize];
            float max = Mathf.Max(0.01f, config.maxDanger);
            for (int y = 0; y < ImageSize; y++)
            {
                for (int x = 0; x < ImageSize; x++)
                {
                    Vector3 world = PixelToWorld(x, y);
                    Color c = Flyable(new Vector3(world.x, 0f, world.z)) ? new Color(0.93f, 0.93f, 0.9f) : new Color(0.55f, 0.55f, 0.55f);
                    float danger = map.GetDanger(world) / max;
                    if (danger > 0.001f)
                        c = Color.Lerp(c, new Color(0.9f, 0.1f, 0.05f), Mathf.Clamp01(0.15f + danger));
                    pixels[y * ImageSize + x] = c;
                }
            }

            DrawPolyline(pixels, clear, new Color32(40, 90, 230, 255));
            DrawPolyline(pixels, careful, new Color32(20, 160, 60, 255));
            DrawDot(pixels, home, 6, new Color32(255, 255, 255, 255), new Color32(0, 0, 0, 255));
            Vector3 side = Vector3.Cross(Vector3.up, killDir);
            for (int i = -1; i <= 1; i++)
                DrawDot(pixels, home + killDir * KillDistance + side * (i * 1.5f), 3, new Color32(0, 0, 0, 255), new Color32(0, 0, 0, 255));

            texture.SetPixels32(pixels);
            texture.Apply();
            Directory.CreateDirectory(Path.GetDirectoryName(file));
            File.WriteAllBytes(file, texture.EncodeToPNG());
            Destroy(texture);
        }

        private Vector3 PixelToWorld(int x, int y)
        {
            float scale = ImageMetres / ImageSize;
            return new Vector3(home.x - ImageMetres * 0.5f + (x + 0.5f) * scale, home.y + FlyHeight,
                home.z - ImageMetres * 0.5f + (y + 0.5f) * scale);
        }

        private Vector2Int WorldToPixel(Vector3 world)
        {
            float scale = ImageSize / ImageMetres;
            return new Vector2Int(Mathf.RoundToInt((world.x - home.x + ImageMetres * 0.5f) * scale),
                Mathf.RoundToInt((world.z - home.z + ImageMetres * 0.5f) * scale));
        }

        private void DrawPolyline(Color32[] pixels, List<Vector3> path, Color32 colour)
        {
            for (int i = 1; i < path.Count; i++)
            {
                Vector2Int a = WorldToPixel(path[i - 1]), b = WorldToPixel(path[i]);
                int steps = Mathf.Max(1, Mathf.Max(Mathf.Abs(b.x - a.x), Mathf.Abs(b.y - a.y)));
                for (int s = 0; s <= steps; s++)
                {
                    Vector2 p = Vector2.Lerp(a, b, s / (float)steps);
                    for (int dy = -1; dy <= 1; dy++)
                    for (int dx = -1; dx <= 1; dx++)
                        Plot(pixels, Mathf.RoundToInt(p.x) + dx, Mathf.RoundToInt(p.y) + dy, colour);
                }
            }
        }

        private void DrawDot(Color32[] pixels, Vector3 world, int radius, Color32 fill, Color32 edge)
        {
            Vector2Int c = WorldToPixel(world);
            for (int dy = -radius - 1; dy <= radius + 1; dy++)
            for (int dx = -radius - 1; dx <= radius + 1; dx++)
            {
                float d = Mathf.Sqrt(dx * dx + dy * dy);
                if (d <= radius) Plot(pixels, c.x + dx, c.y + dy, fill);
                else if (d <= radius + 1) Plot(pixels, c.x + dx, c.y + dy, edge);
            }
        }

        private static void Plot(Color32[] pixels, int x, int y, Color32 colour)
        {
            if (x >= 0 && y >= 0 && x < ImageSize && y < ImageSize)
                pixels[y * ImageSize + x] = colour;
        }

        // ---------- Helpers ----------

        private CrowBrain Spawn(Vector3 position)
        {
            GameObject crow = Instantiate(crowPrefab, position, Quaternion.identity);
            spawned.Add(crow);
            return crow.GetComponent<CrowBrain>();
        }

        private static void Despawn(CrowBrain crow)
        {
            if (crow != null)
                Destroy(crow.gameObject);
        }

        private static void SetPickupsActive(bool active)
        {
            foreach (Pickup pickup in FindObjectsByType<Pickup>(FindObjectsInactive.Include))
                pickup.gameObject.SetActive(active);
        }

        private static float Wrap(float degrees) => Mathf.DeltaAngle(0f, degrees);

        private void Line(string text = "") => report.AppendLine(text);

        private void WriteReport()
        {
            string file = Path.Combine(OutputFolder, "evidence.md");
            Directory.CreateDirectory(OutputFolder);
            File.WriteAllText(file, report.ToString());
            Debug.Log($"[CrowEvidence] Finished — results in {file} and {OutputFolder}/path_comparison.png");
        }

        private void Cleanup()
        {
            foreach (GameObject crow in spawned)
                if (crow != null)
                    Destroy(crow);
            SetPickupsActive(true);
        }
    }
